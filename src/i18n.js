// the browser's language, and otherwise the language the sheet was printed in.
export function initialLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'sq' || q === 'en') return q;
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'sq' || saved === 'en') return saved;
  } catch { /* storage blocked: fall through */ }
  const printed = document.documentElement.lang === 'sq' ? 'sq' : 'en';
  if (location.pathname === '/' || location.pathname === '/index.html') {
    const langs = navigator.languages || [navigator.language || 'en'];
    return langs.some((l) => /^sq\b/i.test(l)) ? 'sq' : 'en';
  }
  return printed;
}

export function rememberLang(lang) {
  try { localStorage.setItem(KEY, lang); } catch { /* private mode */ }
}

// Date and time always in Albania, whatever the visitor's clock says.
// Browsers often ship without Albanian calendar names, so they are set here.
const SQ_DAYS = ['e diel', 'e hënë', 'e martë', 'e mërkurë', 'e enjte', 'e premte', 'e shtunë'];
const SQ_MONTHS = ['janar', 'shkurt', 'mars', 'prill', 'maj', 'qershor', 'korrik', 'gusht', 'shtator', 'tetor', 'nëntor', 'dhjetor'];

export function albaniaNow(lang, short = false) {
  const now = new Date();
  let date;
  if (lang === 'sq') {
    const parts = Object.fromEntries(new Intl.DateTimeFormat('en-GB', {
      weekday: 'short', day: 'numeric', month: 'numeric', year: 'numeric', timeZone: 'Europe/Tirane',
    }).formatToParts(now).map((x) => [x.type, x.value]));
    const wd = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].indexOf(parts.weekday);
    date = `${short ? '' : `${SQ_DAYS[wd]}, `}${parts.day} ${SQ_MONTHS[+parts.month - 1]} ${parts.year}`;
  } else {
    date = new Intl.DateTimeFormat('en-GB', {
      ...(short ? {} : { weekday: 'long' }), day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Europe/Tirane',
    }).format(now);
  }
  const time = new Intl.DateTimeFormat('en-GB', {
    hour: '2-digit', minute: '2-digit', hour12: false, timeZone: 'Europe/Tirane',
  }).format(now);
  const seconds = new Intl.DateTimeFormat('en-GB', { second: '2-digit', timeZone: 'Europe/Tirane' }).format(now);
  return { date, time, seconds: seconds.padStart(2, '0') };
}

// Pour a dictionary into the page. [data-i18n] takes text, [data-i18n-attr]
// takes "attr:key" pairs separated by commas. The title and the description
// are marked the same way on each sheet, so every sheet keeps its own.
export function applyStrings(T, root = document) {
  document.documentElement.lang = T.htmlLang;
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = T[el.dataset.i18n];
    if (typeof v === 'string') el.textContent = v;
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(',').forEach((pair) => {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      const v = T[key];
      if (typeof v === 'string') el.setAttribute(attr, v);
    });
  });
  root.querySelectorAll('[data-i18n-list]').forEach((el) => {
    const [key, idx] = el.dataset.i18nList.split('.');
    const list = T[key];
    if (Array.isArray(list) && typeof list[+idx] === 'string') el.textContent = list[+idx];
  });
}
